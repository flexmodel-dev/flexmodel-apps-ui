export const DEFAULT_APP_ICON: AppIconName = 'Boxes'

export function isAppIconName(value?: string | null): value is AppIconName {
  return !!value && Object.prototype.hasOwnProperty.call(appIcons, value)
}

export function resolveAppIconName(value?: string | null): AppIconName {
  return isAppIconName(value) ? value : DEFAULT_APP_ICON
}

export function resolveAppIcon(value?: string | null): LucideIcon | undefined {
  return isAppIconName(value) ? appIcons[value] : undefined
}
